public class TheSumofEvenNumber{

public static void main(String args []){

int sum =0;
int i =2;  // Start from the first even number

     // While loop to iterate through even numbers 
while(i<=100)
{
sum += i;
i += 2; // Increment by 2 to get the next even number 

}
System.out.println(" the Sum of all Even number is."+sum);

}






}